"""Pydantic v2 schemas and canonical enums for DevLab Guard violation reporting.

Module: devlab_guard.core.models
"""

from enum import StrEnum

from pydantic import BaseModel, Field


class Severity(StrEnum):
    """Severity classification for policy violations."""

    INFO = "INFO"
    WARNING = "WARNING"
    ERROR = "ERROR"
    CRITICAL = "CRITICAL"


class ViolationCategory(StrEnum):
    """Categorical taxonomy for architectural and security policy infractions."""

    ARCHITECTURE = "ARCHITECTURE"
    SECURITY = "SECURITY"
    LEGAL = "LEGAL"
    TYPING = "TYPING"


class Violation(BaseModel):
    """Individual code violation identified by an AST or SAST evaluation rule."""

    rule_id: str = Field(description="Unique rule identifier e.g. ARCH001")
    category: ViolationCategory = Field(description="Category of the violation")
    severity: Severity = Field(description="Severity impact of the violation")
    file_path: str = Field(description="Relative or absolute path to the violating file")
    line_number: int = Field(ge=1, description="1-indexed line number where violation occurs")
    column: int = Field(default=0, ge=0, description="Column index where violation starts")
    message: str = Field(description="Human-readable explanation of why the rule failed")
    suggested_fix: str | None = Field(
        default=None, description="Actionable remediation recommendation"
    )
    code_snippet: str | None = Field(
        default=None, description="Problematic snippet extracted from source"
    )


class RuleResult(BaseModel):
    """Intermediate execution result aggregated from a single rule evaluator."""

    rule_id: str
    violations: list[Violation] = Field(default_factory=list)


class GuardReport(BaseModel):
    """Comprehensive evaluation report summarizing whole repository health and scan results."""

    total_files_scanned: int = Field(ge=0)
    total_violations: int = Field(ge=0)
    passed: bool = Field(description="True if zero ERROR or CRITICAL violations were detected")
    violations: list[Violation] = Field(default_factory=list)
    suggested_diff_patch: str | None = Field(
        default=None, description="Unified git diff patch generated by LLM reasoning"
    )
    execution_time_ms: float = Field(ge=0.0)
